import assert from 'node:assert/strict';
import {executeCase,enterCards,restart} from '../helpers.mjs';
import {observe,evidence,step,questionFixture,questionTitle,directFixture,directTitle,scope,openDetail} from './core-support.mjs';
const id=process.argv[2],out=process.argv[3];
if(!['REVIEW-01','REVIEW-05'].includes(id)||!out)throw Error('UNSUPPORTED_LEARNING_CASE');
await executeCase(id,out,async ctx=>{
  await observe(ctx);await enterCards(ctx);let p=ctx.session.page;
  const card=id==='REVIEW-01'?scope(ctx):ctx.fixture.direct;
  const title=id==='REVIEW-01'?questionTitle:directTitle;
  const history=async()=>(await ctx.session.api.call('learning.history.list',card)).items;
  const before=await history();
  await p.getByRole('checkbox',{name:'选择 '+title,exact:true}).check();
  await p.getByRole('button',{name:'学习选中卡片',exact:true}).click();
  await p.getByRole('heading',{name:title,exact:true}).waitFor();
  if(id==='REVIEW-01'){
    await p.getByRole('radio',{name:'甲正确',exact:true}).check();
    await p.getByLabel('独立思路',{exact:true}).fill('T1-A independent thought');
    await p.getByTestId('review-save-state').filter({hasText:'草稿已保存'}).waitFor();
  }else assert.equal(await p.locator('.review-option').count(),0);
  const resume=p.getByRole('button',{name:'继续计时',exact:true});if(await resume.isVisible())await resume.click();
  await p.getByRole('button',{name:'揭示答案',exact:true}).click();
  const slider=p.getByRole('slider');await slider.waitFor();await slider.focus();await slider.press('Home');for(let i=0;i<80;i++)await slider.press('ArrowRight');
  await p.getByLabel('反思（可选）',{exact:true}).fill('T1-A review persistence');
  await p.getByTestId('review-save-state').filter({hasText:'草稿已保存'}).waitFor();
  if(await resume.isVisible())await resume.click();
  await p.getByRole('button',{name:'保存本次复盘',exact:true}).click();
  await p.getByRole('status').filter({hasText:'复盘已保存 · 自评 8.0'}).waitFor();
  const after=await history();assert.equal(after.length,before.length+1);
  const event=after.find(x=>!before.some(b=>b.eventId===x.eventId));assert.ok(event);
  const detail=await ctx.session.api.call('learning.history.get',{...card,eventId:event.eventId});
  assert.equal(detail.scoreTenths,80);assert.equal(detail.objectiveCorrect,id==='REVIEW-01'?true:null);assert.equal(detail.rating,'good');
  if(id==='REVIEW-01')assert.ok(JSON.stringify(detail).includes('T1-A independent thought'));
  assert.ok(JSON.stringify(detail).includes('T1-A review persistence'));
  const scheduling=await ctx.session.api.call('card.listSummary',{deckId:ctx.fixture.deck.id,limit:100});
  const row=scheduling.items.find(x=>x.cardId===card.cardId);assert.ok(row.dueAt);
  step(ctx,'GUI selects card, answers/reveals, keyboard scores 8.0, submits; IPC confirms one event, correct mode and Good schedule');
  await p.getByRole('button',{name:'返回卡片列表',exact:true}).click();await openDetail(ctx,title);
  await p.getByRole('button',{name:'查看学习历史',exact:true}).click();
  await p.locator('.detail-history-list button').first().click();
  await p.getByRole('region',{name:'当次复盘证据'}).count();
  assert.ok((await p.locator('[aria-label="当次复盘证据"]').innerText()).includes('T1-A review persistence'));
  const reboot=await restart(ctx);p=ctx.session.page;await observe(ctx);await enterCards(ctx);await openDetail(ctx,title);
  await p.getByRole('button',{name:'查看学习历史',exact:true}).click();await p.locator('.detail-history-list button').first().click();
  assert.ok((await p.locator('[aria-label="当次复盘证据"]').innerText()).includes('T1-A review persistence'));
  assert.deepEqual(await ctx.session.api.call('learning.history.get',{...card,eventId:event.eventId}),detail);
  assert.equal((await ctx.session.api.call('card.listSummary',{deckId:ctx.fixture.deck.id,limit:100})).items.find(x=>x.cardId===card.cardId).dueAt,row.dueAt);
  step(ctx,'GUI history reopened before/after new PID; exact event and dueAt survive restart');
  return {...await evidence(ctx),reboot,eventId:event.eventId};
},{fixtureSetup:id==='REVIEW-01'?questionFixture:directFixture});
