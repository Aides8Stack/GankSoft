import { z } from "zod";
export const Diagnosis = z.strictObject({
  status: z.enum([
    "unseen",
    "stale",
    "improving",
    "insufficient",
    "weak",
    "suspected_weak",
    "stable",
    "unstable",
  ]),
  risk: z.number().min(0).max(1).nullable(),
  confidence: z.number().min(0).max(1),
  coverage: z.number().min(0).max(1),
  coverageGap: z.boolean(),
  effectiveEvidenceN: z.number(),
  good: z.number(),
  bad: z.number(),
  distinctCards: z.number().int(),
  distinctDays: z.number().int(),
  observations: z.number().int(),
  invalidEvents: z.number().int(),
  stale: z.boolean(),
  improving: z.boolean(),
  faults: z.record(z.string(), z.number()),
  reasonCodes: z.array(z.string()),
});
export const DeckDiagnosis = z.strictObject({
  questionTotal: z.number().int(),
  knowledgeTotal: z.number().int(),
  knowledgeOffset: z.number().int(),
  ruleVersion: z.string(),
  ruleRevision: z.number().int(),
  calculatedAt: z.iso.datetime(),
  timezone: z.string(),
  dataRevision: z.string(),
  unknownLinkHistoryCount: z.number().int(),
  unattributedFailureCount: z.number().int(),
  questions: z.array(Diagnosis.extend({ cardId: z.string() })),
  knowledge: z.array(
    Diagnosis.extend({
      knowledgeId: z.string(),
      name: z.string(),
      parentId: z.string().nullable(),
    }),
  ),
});
export const QueueItem = z.strictObject({
  cardId: z.string(),
  kind: z.enum(["question", "memory"]),
  dueAt: z.iso.datetime(),
  overdue: z.number(),
  severe: z.boolean(),
  questionRisk: z.number(),
  knowledgeRisk: z.number(),
  coverage: z.number(),
  knowledgeIds: z.array(z.string()),
  fatigue: z.boolean(),
  specialtyBoost: z.number(),
  reasonCodes: z.array(z.string()),
  score: z.number(),
});
export const QueuePreview = z.strictObject({
  deckId: z.string(),
  ruleVersion: z.string(),
  configRevision: z.number().int(),
  calculatedAt: z.iso.datetime(),
  timezone: z.string(),
  seed: z.string(),
  dataRevision: z.string(),
  budgets: z.strictObject({
    uniqueDueUsed: z.number(),
    relearnUsed: z.number(),
    practiceUsed: z.number(),
    dueLeft: z.number(),
    relearnLeft: z.number(),
    specialtyLeft: z.number(),
    practiceMinutes: z.number(),
  }),
  due: z.array(QueueItem),
  relearn: z.array(QueueItem),
  specialty: z.array(QueueItem),
  excluded: z.record(z.string(), z.number()),
  diagnosis: DeckDiagnosis.nullable(),
});
